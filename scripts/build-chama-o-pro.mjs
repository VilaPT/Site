import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const projectRoot = path.resolve(path.dirname(scriptPath), '..');
const previewRoot = path.join(projectRoot, 'chamaopro-preview');

export const cssSources = [
  'styles.css',
  'account.css',
  'base-overrides.css',
  'community18.css',
  'brand20.css',
  'ux24.css',
  'ux25.css',
  'verification29.css',
  'profile30.css',
  'chat31.css',
  'appointment32.css',
  'ux33.css',
  'ux34.css',
  'directchat35.css',
  'homepage36.css',
  'homepage37.css',
  'business37.css',
  'social38.css',
  'professional-activity.css',
  'admin-control.css',
  'reports.css',
  'owner-console.css',
  'owner-district-multi.css',
  'auth-viewport.css',
  'pro-editor-viewport.css',
  'platform-transition.css',
  'feature13.css',
];

export async function composePlatformCss() {
  const sections = await Promise.all(cssSources.map(async (source) => {
    const contents = await readFile(path.join(previewRoot, source), 'utf8');
    return `/* source: ${source} */\n${contents.trim()}\n`;
  }));

  return [
    '/* Generated by scripts/build-chama-o-pro.mjs. Edit the source files, not this bundle. */',
    '',
    ...sections,
  ].join('\n');
}

export async function buildPlatformCss() {
  const output = await composePlatformCss();
  await writeFile(path.join(previewRoot, 'platform.css'), output, 'utf8');
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  await buildPlatformCss();
  console.log(`Chama O Pro CSS: ${cssSources.length} fontes reunidas em platform.css`);
}
